// The source of src/lib/db.ts in every project: the app's built-in data store. Inside Buildr's
// preview it asks the page around it (postMessage) to read and write the project's records, which
// are stored per project and visible only to the project's owner. Anywhere else (the exported
// code, a shared read-only preview) it falls back to this browser's localStorage, then to memory,
// so the same code keeps working. Written without backticks so it can live in a template string.
export const DB_HELPER_PATH = "src/lib/db.ts";

export const DB_HELPER_SOURCE = [
  "// Built-in data store. Collections hold plain JSON objects (up to 16 KB each, 1,000 per app).",
  '// Use: const todos = await db.list("todos"); await db.create("todos", { title: "x" });',
  "// Collection names: lowercase letters, digits, - and _ (max 40).",
  "export type DbRecord<T extends object = Record<string, unknown>> = T & {",
  "  id: string;",
  "  createdAt: string;",
  "  updatedAt: string;",
  "};",
  "",
  'type Op = "list" | "create" | "update" | "remove";',
  "type Reply = { ok: boolean; code?: string; message?: string; result?: unknown };",
  "",
  'const inFrame = typeof window !== "undefined" && window.parent !== window;',
  "const waiting = new Map<string, (reply: Reply) => void>();",
  "let counter = 0;",
  "",
  "if (inFrame) {",
  '  window.addEventListener("message", (event) => {',
  "    if (event.source !== window.parent) return;",
  "    const data = event.data as { type?: string; id?: string } & Reply;",
  '    if (!data || data.type !== "buildr-data-result" || typeof data.id !== "string") return;',
  "    waiting.get(data.id)?.(data);",
  "    waiting.delete(data.id);",
  "  });",
  "}",
  "",
  "function ask(op: Op, collection: string, recordId?: string, data?: object): Promise<Reply> {",
  "  return new Promise((resolve) => {",
  '    const id = "q" + ++counter;',
  "    const timer = setTimeout(() => {",
  "      waiting.delete(id);",
  '      resolve({ ok: false, code: "unavailable" });',
  "    }, 8000);",
  "    waiting.set(id, (reply) => {",
  "      clearTimeout(timer);",
  "      resolve(reply);",
  "    });",
  '    window.parent.postMessage({ type: "buildr-data", id, op, collection, recordId, data }, "*");',
  "  });",
  "}",
  "",
  "// Local fallback: this browser only.",
  "const memory = new Map<string, DbRecord[]>();",
  "function readLocal(collection: string): DbRecord[] {",
  "  try {",
  '    const raw = window.localStorage.getItem("db:" + collection);',
  "    if (raw) return JSON.parse(raw) as DbRecord[];",
  "  } catch {",
  "    // storage is blocked: use memory",
  "  }",
  "  return memory.get(collection) ?? [];",
  "}",
  "function writeLocal(collection: string, rows: DbRecord[]) {",
  "  memory.set(collection, rows);",
  "  try {",
  '    window.localStorage.setItem("db:" + collection, JSON.stringify(rows));',
  "  } catch {",
  "    // storage is blocked: memory only",
  "  }",
  "}",
  "function local(op: Op, collection: string, recordId?: string, data?: object): unknown {",
  "  const rows = readLocal(collection);",
  "  const now = new Date().toISOString();",
  '  if (op === "list") return rows;',
  '  if (op === "create") {',
  "    const row = { ...data, id: crypto.randomUUID(), createdAt: now, updatedAt: now } as DbRecord;",
  "    writeLocal(collection, [...rows, row]);",
  "    return row;",
  "  }",
  '  if (op === "update") {',
  "    const next = rows.map((row) =>",
  "      row.id === recordId ? ({ ...row, ...data, id: row.id, createdAt: row.createdAt, updatedAt: now } as DbRecord) : row,",
  "    );",
  "    writeLocal(collection, next);",
  "    return next.find((row) => row.id === recordId) ?? null;",
  "  }",
  "  writeLocal(collection, rows.filter((row) => row.id !== recordId));",
  "  return null;",
  "}",
  "",
  "async function run(op: Op, collection: string, recordId?: string, data?: object): Promise<unknown> {",
  "  if (inFrame) {",
  "    const reply = await ask(op, collection, recordId, data);",
  "    if (reply.ok) return reply.result;",
  '    if (reply.code !== "unavailable") throw new Error(reply.message ?? "The data store could not do that.");',
  "  }",
  "  return local(op, collection, recordId, data);",
  "}",
  "",
  "export const db = {",
  "  list: <T extends object = Record<string, unknown>>(collection: string) =>",
  '    run("list", collection) as Promise<DbRecord<T>[]>,',
  "  create: <T extends object>(collection: string, data: T) =>",
  '    run("create", collection, undefined, data) as Promise<DbRecord<T>>,',
  "  update: <T extends object>(collection: string, id: string, data: Partial<T>) =>",
  '    run("update", collection, id, data) as Promise<DbRecord<T>>,',
  '  remove: (collection: string, id: string) => run("remove", collection, id).then(() => undefined),',
  "};",
  "",
].join("\n");
